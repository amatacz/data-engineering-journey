-- create dim_location
create table if not exists dw.dim_location_scd2(
	location_key integer generated by default as identity primary key,
	location_id integer not null,
	borough text,
	zone text,
	service_zone text,
	valid_from date not null,
	valid_to date not null,
	is_current boolean not null
);

insert into dw.dim_location_scd2 (
	location_key,
	location_id,
	borough,
	zone,
	service_zone,
	valid_from,
	valid_to,
	is_current
)
values (-1, -1, 'Unknown', 'Unknown', 'Unknown', '1900-01-01', '9999-12-31', true)
on conflict do nothing;

-- create indexes
-- drop index dw.idx_dim_location_location_id_current;
-- drop index dw.idx_dim_location_location_location_id_valid_from;

create unique index if not exists idx_dim_location_location_id_current
on dw.dim_location_scd2(location_id)
where is_current = true;

create index if not exists idx_dim_location_location_id_valid_from
on dw.dim_location_scd2(location_id, valid_from);

insert into dw.dim_location_scd2 (
    location_id,
    borough,
    zone,
    service_zone,
    valid_from,
    valid_to,
    is_current
)
select
    txz.location_id,
    txz.borough,
    txz.zone,
    txz.service_zone,
    '1900-01-01',
    '9999-12-31',
    true
from staging.taxi_zones_v1 txz
WHERE NOT EXISTS (
    SELECT 1 
    FROM dw.dim_location_scd2 d
    WHERE d.location_id = txz.location_id
);
