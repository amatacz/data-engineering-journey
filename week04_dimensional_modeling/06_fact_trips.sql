create table if not exists dw.fact_trips(
	trip_key integer generated by default as identity primary key,
	
	-- klucze obce
	pickup_date_key integer not null,
	pickup_time_key integer not null,
	dropoff_date_key integer not null,
	dropoff_time_key integer not null,
	pickup_location_key integer not null,
	dropoff_location_key integer not null,
	vendor_key integer not null,
	payment_type_key integer not null,
	
	-- miary
	passenger_count integer,
	trip_distance numeric(10,2),
	fare_amount numeric(10,2),
	tip_amount numeric(10,2),
	tolls_amount numeric(10,2),
	total_amount numeric(10,2),
	
	--miara wyliczana: trip_duration_minutes = różnica dropoff − pickup w minutach
	trip_duration_minutes numeric(10,2),
	constraint fk_fact_trips_pickup_date
		foreign key(pickup_date_key) references dw.dim_date(date_key),
	constraint fk_fact_trips_pickup_time
		foreign key(pickup_time_key) references dw.dim_time(time_key),
	constraint fk_fact_trips_dropoff_date
		foreign key(dropoff_date_key) references dw.dim_date(date_key),
	constraint fk_fact_trips_dropoff_time
		foreign key(dropoff_time_key) references dw.dim_time(time_key),
	constraint fk_fact_trips_pickup_location_key
		foreign key(pickup_location_key) references dw.dim_location_scd2(location_key),
	constraint fk_fact_trips_dropoff_location_key
		foreign key(dropoff_location_key) references dw.dim_location_scd2(location_key),
	constraint fk_fact_trips_vendor_key
		foreign key(vendor_key) references dw.dim_vendor(vendor_key),
	constraint fk_fact_payment_type_key
		foreign key(payment_type_key) references dw.dim_payment_type(payment_type_key)	
);

truncate table dw.fact_trips;

insert into dw.fact_trips(pickup_date_key, pickup_time_key, dropoff_date_key, dropoff_time_key, pickup_location_key, 
							dropoff_location_key, vendor_key, payment_type_key, passenger_count, trip_distance, fare_amount, 
							tip_amount, tolls_amount, total_amount, trip_duration_minutes)
select 
	to_char(yt.tpep_pickup_datetime, 'YYYYMMDD')::integer as pickup_date_key,
	((EXTRACT(hour from yt.tpep_pickup_datetime)*100) + extract(minute from yt.tpep_pickup_datetime))::integer as pickup_time_key,
	to_char(yt.tpep_dropoff_datetime, 'YYYYMMDD')::integer as dropoff_date_key,
	((EXTRACT(hour from yt.tpep_dropoff_datetime)*100) + extract(minute from yt.tpep_dropoff_datetime))::integer as dropoff_time_key,
	coalesce(pu.location_key, -1) as pickup_location_key,
	coalesce(d1.location_key, -1) as dropoff_location_key,
	coalesce(v.vendor_key , -1) as vendor_key,
	coalesce(p.payment_type_key , -1) as payment_type_key,
	yt.passenger_count, yt.trip_distance, yt.fare_amount, 
	yt.tip_amount, yt.tolls_amount, yt.total_amount,
	ROUND(EXTRACT(EPOCH FROM (yt.tpep_dropoff_datetime - yt.tpep_pickup_datetime)) / 60.0, 2) as trip_duration_minutes
from
	staging.yellow_trips yt 
	left join dw.dim_vendor v on yt."VendorID" = v.vendor_id 
	left join dw.dim_payment_type p on yt.payment_type = p.payment_type_id 
	left join dw.dim_location_scd2 pu on yt."PULocationID" = pu.location_id
		and yt.tpep_pickup_datetime::date >= pu.valid_from AND yt.tpep_pickup_datetime::date < pu.valid_to
	left join dw.dim_location_scd2 d1 on yt."DOLocationID" = d1.location_id
		and yt.tpep_pickup_datetime::date >= d1.valid_from AND yt.tpep_pickup_datetime::date < d1.valid_to
where 
	date(yt.tpep_pickup_datetime) >= (select min(full_date) from dw.dim_date where date_key <> -1)
	and date(yt.tpep_pickup_datetime) <= (select MAX(full_date) from dw.dim_date)
	and yt.tpep_dropoff_datetime > yt.tpep_pickup_datetime
	and yt.trip_distance > 0 AND yt.trip_distance <= 100
	and yt.fare_amount >= 0;